"""IT分野の5軸プロファイル。

各分野を [クリエイティブ, ロジカル, 作る↔運用, 数学, 計画性・正確さ] の
5軸ベクトルで表す。

値はO*NETの職業別記述子から導出した0.25刻みの5段階で、
「10分野の中でその軸がどれくらい強いか」を表す相対値である。
導出の手順と根拠データは docs/field_profile_rationale.md にある。
"""

import numpy as np


#                        クリエ ロジカル 作る↔運用 数学  計画性
field_profile = {
    "UI/UXデザイン":        [0.75, 0.25, 0.75, 0.25, 0.25],
    "グラフィックデザイン":  [1.00, 0.00, 1.00, 0.00, 0.25],
    "Webサイト管理":         [0.25, 0.75, 0.25, 0.25, 0.75],
    "フロントエンド":        [0.25, 0.50, 0.50, 0.25, 0.25],
    "バックエンド":          [0.25, 0.75, 0.25, 0.25, 0.25],
    "モバイルアプリ":        [0.25, 0.50, 0.25, 0.25, 0.25],
    "ゲーム開発":            [1.00, 0.50, 1.00, 0.25, 0.00],
    "データ/ML":             [0.25, 1.00, 0.00, 1.00, 0.75],
    "インフラ/クラウド":     [0.25, 0.50, 0.00, 0.50, 0.75],
    "QA・テスト":            [0.00, 1.00, 0.25, 0.25, 1.00],
}

field_names = list(field_profile.keys())

# 分野×5軸の行列
F = np.array([field_profile[field] for field in field_names], dtype=float)

field_index = {field: i for i, field in enumerate(field_names)}

# 各分野について「最も適性のない人」までの平均二乗距離。
#
#   max_distance_f = mean_a( max(F_fa, 1 - F_fa)^2 )
#
# 適性値は0～1なので、軸aで最も離れられるのは0か1のどちらか遠い方であり、
# その二乗を5軸で平均した値がその分野が取りうる距離の上限になる。
#
# 相性はこの上限で割って正規化する（calculation/recommend.py）。
# 割らずに 1 - 距離 とすると、プロファイルが中央(0.5)に寄った分野ほど
# 誰に対しても高い相性を返す（平均相性 = 0.8333 - mean((F-0.5)^2) が恒等的に成り立つ）。
# つまり「性格像を鮮明に書くほど推薦されにくくなる」という逆転が起きるため、
# 分野ごとの尺度を揃えてからしきい値と比較する。
field_max_distance = np.mean(np.maximum(F, 1.0 - F) ** 2, axis=1)
