"""適性5軸の定義と、推薦計算で使う係数。"""

# ============================================================
# 適性5軸
# ============================================================

axis_names = [
    "クリエイティブ",
    "ロジカル",
    "作る↔運用",
    "数学",
    "計画性・正確さ",
]

# クリエイティブ・ロジカル・数学・計画性：
#
#   1.0 = 高い
#   0.5 = 中程度
#   0.0 = 低い
#
# 作る↔運用：
#
#   1.0 = 作る側
#   0.5 = 中間
#   0.0 = 運用側

LOW = 0.0
MID = 0.5
HIGH = 1.0


# ============================================================
# 推薦計算の係数（デフォルト値）
# ============================================================

# 項目価値へ反映させる分野相性の最低値。
# これ未満の分野は項目価値への寄与を0にする。
DEFAULT_MIN_RELEVANCE = 0.60

# 予算制約ペナルティ係数の安全マージン。
# ペナルティ係数 A は「予算を1単位超えて解放できる真の報酬の上限
# （単一項目の限界寄与 max_j(V_j + Σ正シナジー)）」に等しいと、
# 実行可能解と1単位違反解が同点になり得る。
# 厳密に実行可能解を優先させるため、(1 + このマージン) を掛ける。
# 目的差（0.15〜2.4）を埋め戻して桁差を再現しないよう、十分小さくする。
DEFAULT_PENALTY_MARGIN = 0.01

# アニーリング設定
DEFAULT_NUM_READS = 5000
DEFAULT_NUM_SWEEPS = 5000
DEFAULT_SEED = 42


# ============================================================
# D-Wave 実機 QPU の設定
# ============================================================

# QPUの実行回数。
# QPUはマシン時間が課金対象（Leap無料枠は月1分）で、
# 1回の読み出しにアニール＋読み出しで100マイクロ秒程度かかる。
# nealと同じ5000回は無料枠の1割弱を1実行で使うため、既定は控えめにする。
DEFAULT_QPU_NUM_READS = 100

# 1回のアニーリングにかける時間（マイクロ秒）。
# D-Waveの既定値は20マイクロ秒。長くすると断熱条件に近づくが、
# その分だけ消費するマシン時間も増える。
DEFAULT_ANNEALING_TIME = 20

# 使用するQPUの機種名。
# Noneの場合はLeapが利用可能なQPUを自動で選ぶ。
# 例："Advantage_system6"（Pegasus, 5760量子ビット）
#     "Advantage2_system1"（Zephyr, 4800量子ビット）
DEFAULT_QPU_SOLVER = None
