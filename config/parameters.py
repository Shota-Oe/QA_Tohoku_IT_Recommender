# 項目価値へ反映させる分野相性の最低値。
# これ未満の分野は項目価値への寄与を0にする。
DEFAULT_MIN_RELEVANCE = 0.60

# 予算制約ペナルティ係数の安全マージン。
# ペナルティ係数 A は「予算を1単位超えて解放できる真の報酬の上限
# （単一項目の限界寄与 max_j(V_j + Σ正シナジー)）」に等しいと、
# 実行可能解と1単位違反解が同点になり得る。
# 厳密に実行可能解を優先させるため、(1 + このマージン) を掛ける。
# 目的差（0.15〜2.4）を埋め戻して桁差を再現しないよう、十分小さくする。
DEFAULT_PENALTY_MARGIN = 0.01

